#!/usr/bin/env python3
"""Generate the ProgramBench fleet base compose (infra + one agent and one
mini-router sidecar per worker) for the 1-team shape the launchers run:
PBENCH_WORKERS_PER_TEAM peer coders named ${ORG_NAME}-worker<i>.
There is no director, lead, reviewer or auditor.

Agent names use ${ORG_NAME} as prefix so a single template can be re-deployed N
times by varying ORG_NAME (+ ports / DATA_ROOT / secrets) per instance. The
anti-cheat agent block (0111 reference-binary mount + non-root uid) is baked
into every agent, so any size stays egress-locked.

The Makefile renders this per profile (`make render-pbench-base`, also run by
`make up PROFILE=pbench-*`) into docker/_gen-prod.<profile>.yml.
Everything per worker (resource guard, prompt mounts, board env) and the
board-service are emitted here; docker-compose.pbench.yml adds only the
egress lock. There is no per-N overlay to keep in step with the worker count.
"""
import os
import sys

# ---- TOPOLOGY (env-driven) ----------------------------------------------------
#   PBENCH_WORKERS_PER_TEAM number of workers (default 16)
WORKERS_PER_TEAM = int(os.environ.get("PBENCH_WORKERS_PER_TEAM") or 16)

def agent_names():
    """Return list of (short_name, role) for the configured topology."""
    return [(f"worker{w}", "coder") for w in range(1, WORKERS_PER_TEAM + 1)]

ALL_AGENTS = agent_names()

