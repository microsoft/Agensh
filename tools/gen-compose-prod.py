#!/usr/bin/env python3
"""Generate a ProgramBench fleet compose (infra + per-agent hermes + mini-router
sidecars) from an env-driven topology. Defaults reproduce the original 37-agent
layout (1 director + 1 auditor + 5 leads + 5 reviewers + 25 workers); set
PBENCH_TEAMS / PBENCH_WORKERS_PER_TEAM / PBENCH_AUDITOR to deploy a smaller team.

Agent names use ${ORG_NAME} as prefix so a single template can be re-deployed N
times by varying ORG_NAME (+ ports / DATA_ROOT / secrets) per instance. The
anti-cheat agent block (0111 reference-binary mount + non-root uid) is baked
into every agent, so any topology stays egress-locked.

The Makefile renders this per-profile at `make up PROFILE=org-pbench*` into
docker/generated/prod.<profile>.yml. To regenerate the committed default
template by hand:
    python3 tools/gen-compose-prod.py > docker/docker-compose.prod.yml
"""
import os
import sys

# ---- TOPOLOGY (env-driven; defaults reproduce the original 37-agent layout) --
# Set these in .env.<profile> (or the process env) to deploy a smaller team
# without touching this script. Empty/unset → the default below.
#   PBENCH_TEAMS            number of teams      (default 5)
#   PBENCH_WORKERS_PER_TEAM workers per team     (default 5)
#   PBENCH_AUDITOR          "1" keep auditor, "0" drop it (default "1")
# Each team is always 1 lead + 1 reviewer + N workers; 1 director is always
# present. The anti-cheat agent block (0111 reference-binary mount, non-root
# uid) is baked into every agent block, so any topology stays egress-locked.
TEAMS            = int(os.environ.get("PBENCH_TEAMS") or 5)
WORKERS_PER_TEAM = int(os.environ.get("PBENCH_WORKERS_PER_TEAM") or 5)
AUDITOR          = (os.environ.get("PBENCH_AUDITOR") or "1") == "1"

# RL selective-training split (empty → no split, all agents share ANTHROPIC_BASE_URL).
# Roles listed here are the *trained* layer: their LLM traffic is routed to ccr
# (→ AGL proxy → vLLM policy) so the proxy records their token-ids. Every other
# role inherits the shared ANTHROPIC_BASE_URL (→ egress-proxy → opus, not trained).
TRAIN_ROLES = {r.strip() for r in (os.environ.get("PBENCH_TRAIN_ROLES") or "").split(",") if r.strip()}

def agent_names():
    """Return list of (short_name, role) for the configured topology."""
    out = [("director", "director")]
    if AUDITOR:
        out.append(("auditor", "auditor"))
    for t in range(1, TEAMS + 1):
        out.append((f"team{t}-lead", "lead"))
        out.append((f"team{t}-reviewer", "reviewer"))
        for w in range(1, WORKERS_PER_TEAM + 1):
            out.append((f"team{t}-worker{w}", "coder"))
    return out

ALL_AGENTS = agent_names()

