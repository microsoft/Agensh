# Quality gates for packs that accept work through CI: the Gitea Actions workflow
# generated from the acceptance commands, and the main-health gate that lets only
# fix-main PRs merge while main fails its full suite (docs/task_pack_design.md).

from dataclasses import dataclass, field
import json
import re

WORKFLOW_PATH = '.gitea/workflows/agensh.yml'
CODEOWNERS_PATH = '.gitea/CODEOWNERS'
# Gitea names an Actions status "<workflow> / <job> (<event>)".
PR_CHECK = 'agensh / pr (pull_request)'
MAIN_CHECK = 'agensh / main (push)'
HEALTH_CHECK = 'agensh/main-health'
# Optional: PRs touching [coordination] review_paths need one peer's approval.
REVIEW_CHECK = 'agensh/review'
REQUIRED_CHECKS = (PR_CHECK, HEALTH_CHECK)
FIX_LABEL = 'fix-main'
# The allowlist network's filtering proxy (docker/network_allowlist.yml).
ALLOWLIST_PROXY = 'http://egress-filter:3128'
# The egress proxy's unmodified route for a project's own model calls.
MODEL_ROUTE = 'http://egress-proxy:4180/raw'
# The final evaluation's route: outside the team's token budget once the driver opens it.
FINAL_MODEL_ROUTE = 'http://egress-proxy:4180/raw-final'
TEAM_ALERT_AFTER = 15 * 60
LIFT_AFTER = 60 * 60


def _job(name, event_condition, commands, timeout_minutes):
    # Only run: steps, so offline teams need no actions from the internet. The
    # repository is public inside the team network, so checkout needs no token.
    lines = [
        f'  {name}:',
        f"    if: gitea.event_name == '{event_condition}'",
        '    runs-on: ubuntu-latest',
        f'    timeout-minutes: {timeout_minutes}',
        '    steps:',
        '      - name: checkout',
        '        run: |',
        '          git init -q .',
        '          git fetch -q --depth=1 "http://gitea:3000/${{ gitea.repository }}.git" "${{ gitea.ref }}"',
        '          git checkout -q FETCH_HEAD',
    ]
    if not commands:
        lines += ['      - name: no checks declared', '        run: echo "no acceptance commands declared"']
    for index, command in enumerate(commands, 1):
        lines += [f'      - name: {json.dumps(f"check {index}: {command}"[:80])}',
                  f'        run: {json.dumps(command)}']
    return lines


def render_workflow(pr_commands, main_commands, timeout_minutes=15, proxy=None, model_route=False):
    """The team's CI: PRs run the fast checks, pushes to main run the full suite.

    With `proxy`, jobs reach package registries through the allowlist proxy; with
    `model_route`, checks may call models through AGENSH_MODEL_BASE.
    """
    env = []
    if proxy:
        env += [*(f'  {name}: {proxy}' for name in ('HTTP_PROXY', 'HTTPS_PROXY', 'http_proxy', 'https_proxy')),
                '  NO_PROXY: gitea,egress-proxy,localhost,127.0.0.1', '  no_proxy: gitea,egress-proxy,localhost,127.0.0.1']
    if model_route:
        env.append(f'  AGENSH_MODEL_BASE: {MODEL_ROUTE}')
    lines = [
        '# Generated by Agensh from the project\'s acceptance checks; removed before delivery.',
        '# Protected: changes need the team administrator.',
        'name: agensh',
        'on:',
        '  pull_request:',
        '  push:',
        '    branches: [main]',
        *(['env:', *env] if env else []),
        'defaults:',
        '  run:',
        '    shell: bash',
        'jobs:',
        *_job('pr', 'pull_request', pr_commands, timeout_minutes),
        *_job('main', 'push', main_commands, timeout_minutes),
    ]
    return '\n'.join(lines) + '\n'


def glob_regex(pattern):
    # Protected-path globs (Gitea's protected-file syntax) as an anchored regular
    # expression, for CODEOWNERS (which takes Go regexps) and the delivery report.
    out, i = '^', 0
    while i < len(pattern):
        if pattern.startswith('**', i):
            out, i = out + '.*', i + 2
        elif pattern[i] == '*':
            out, i = out + '[^/]*', i + 1
        elif pattern[i] == '?':
            out, i = out + '[^/]', i + 1
        else:
            out, i = out + re.escape(pattern[i]), i + 1
    return out + '$'


def matches_any(path, patterns):
    return any(re.match(glob_regex(p), path) for p in patterns)


def render_codeowners(patterns, owner):
    lines = ['# Generated by Agensh: protected paths need the product owner\'s approval;',
             '# removed before delivery.']
    lines += [f'{glob_regex(p)} @{owner}' for p in patterns]
    return '\n'.join(lines) + '\n'


def is_fix_pr(pull):
    labels = {label.get('name') for label in pull.get('labels') or []}
    return FIX_LABEL in labels or str(pull.get('title', '')).lower().startswith(f'[{FIX_LABEL}]')


@dataclass
class HealthGate:
    """Decides alerts and per-PR statuses from the full suite's result on main.

    observe() takes the main check's state for the current main head and returns the
    actions to take, so the timing rules stay testable without Gitea.
    """
    red_since: float = None
    broken_sha: str = ''
    team_alerted: bool = False
    lifted: bool = False
    history: list = field(default_factory=list)

    @property
    def red(self):
        return self.red_since is not None

    def observe(self, state, sha, now):
        actions = []
        if state in ('failure', 'error'):
            if not self.red:
                self.red_since, self.broken_sha = now, sha
                self.team_alerted = self.lifted = False
                actions.append('broken')
            elif not self.team_alerted and now - self.red_since >= TEAM_ALERT_AFTER:
                self.team_alerted = True
                actions.append('alert_team')
            if not self.lifted and now - self.red_since >= LIFT_AFTER:
                self.lifted = True
                actions.append('lift')
        elif state == 'success' and self.red:
            actions.append('recovered')
            self.red_since, self.broken_sha = None, ''
            self.team_alerted = self.lifted = False
        for action in actions:
            self.history.append({'at': now, 'action': action, 'sha': sha})
        return actions

    def pr_status(self, pull):
        """The main-health status a PR head should carry: (state, description)."""
        if not self.red:
            return 'success', 'main passes its full suite'
        if self.lifted:
            return 'success', 'main is still failing; the fix-main restriction lifted after 60 minutes'
        if is_fix_pr(pull):
            return 'success', 'fix-main PR: may merge while main is failing'
        return 'pending', f'main is failing; only {FIX_LABEL} PRs merge until it passes'


def review_status(files, reviews, author, patterns):
    """The agensh/review status for a PR: (state, description).

    Paths rather than changed-line counts decide, because agents could split PRs
    to stay under a size threshold. Only approvals by someone other than the
    author count, and a later change request by the same reviewer withdraws theirs.
    """
    touched = [f for f in files if matches_any(f, patterns)]
    if not touched:
        return 'success', 'no path that needs peer review'
    latest = {}
    for review in sorted(reviews or [], key=lambda r: (r.get('submitted_at') or '', r.get('id', 0))):
        login = (review.get('user') or {}).get('login', '')
        if login and login != author and review.get('state') in ('APPROVED', 'REQUEST_CHANGES'):
            latest[login] = review
    approvers = sorted(login for login, review in latest.items()
                       if review['state'] == 'APPROVED' and not review.get('stale') and not review.get('dismissed'))
    if approvers:
        return 'success', f'approved by {", ".join(approvers)}'
    return 'pending', f'needs one peer approval: touches {", ".join(touched[:3])}' + (' …' if len(touched) > 3 else '')


def check_state(statuses, context):
    """The latest state of one status context, from Gitea's combined status list."""
    matching = [s for s in statuses or [] if s.get('context') == context]
    if not matching:
        return None
    latest = max(matching, key=lambda s: (s.get('updated_at') or s.get('created_at') or '', s.get('id', 0)))
    return latest.get('status') or latest.get('state')
